-- ==============================================================================
-- 1. TABLA ESTUDIANTE (Tabla Base de Usuarios)
-- ==============================================================================
CREATE TABLE Estudiante (
    id_estudiante     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    documento_id      VARCHAR2(20) NOT NULL CONSTRAINT uk_estudiante_doc UNIQUE,
    nombres           VARCHAR2(100) NOT NULL,
    apellidos         VARCHAR2(100) NOT NULL,
    universidad       VARCHAR2(100) NOT NULL,
    programa          VARCHAR2(100) NOT NULL,
    correo            VARCHAR2(150) NOT NULL CONSTRAINT uk_estudiante_correo UNIQUE,
    numero_celular    VARCHAR2(20) NOT NULL
);

-- ==============================================================================
-- 2. TABLA CONDUCTOR (Subentidad / Rol)
-- ==============================================================================
CREATE TABLE Conductor (
    id_conductor      NUMBER PRIMARY KEY,
    CONSTRAINT fk_conductor_estudiante 
        FOREIGN KEY (id_conductor) 
        REFERENCES Estudiante(id_estudiante) 
        ON DELETE CASCADE
);

-- ==============================================================================
-- 3. TABLA PASAJERO (Subentidad / Rol)
-- ==============================================================================
CREATE TABLE Pasajero (
    id_pasajero       NUMBER PRIMARY KEY,
    CONSTRAINT fk_pasajero_estudiante 
        FOREIGN KEY (id_pasajero) 
        REFERENCES Estudiante(id_estudiante) 
        ON DELETE CASCADE
);

-- ==============================================================================
-- 4. TABLA VEHICULO
-- ==============================================================================
CREATE TABLE Vehiculo (
    placa             VARCHAR2(10) PRIMARY KEY,
    marca             VARCHAR2(50) NOT NULL,
    modelo            VARCHAR2(50) NOT NULL,
    anio              NUMBER(4) NOT NULL CONSTRAINT chk_vehiculo_anio CHECK (anio > 1900),
    color             VARCHAR2(30) NOT NULL,
    cupos             NUMBER(2) NOT NULL CONSTRAINT chk_vehiculo_cupos CHECK (cupos > 0),
    id_conductor      NUMBER NOT NULL,
    CONSTRAINT fk_vehiculo_conductor 
        FOREIGN KEY (id_conductor) 
        REFERENCES Conductor(id_conductor)
);

-- ==============================================================================
-- 5. TABLA VIAJE
-- ==============================================================================
CREATE TABLE Viaje (
    id_viaje          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_hora_salida TIMESTAMP NOT NULL,
    fecha_hora_llegada TIMESTAMP,
    punto_origen      VARCHAR2(200) NOT NULL,
    ruta_general      VARCHAR2(500) NOT NULL,
    distancia_km      NUMBER(6,2) CONSTRAINT chk_viaje_distancia CHECK (distancia_km > 0),
    tarifa            NUMBER(10,2) NOT NULL CONSTRAINT chk_viaje_tarifa CHECK (tarifa >= 0),
    estado            VARCHAR2(20) DEFAULT 'Programado' NOT NULL 
                      CONSTRAINT chk_viaje_estado CHECK (estado IN ('Programado', 'En curso', 'Completado', 'Cancelado')),
    cupos_disponibles NUMBER(2) NOT NULL CONSTRAINT chk_viaje_cupos_disp CHECK (cupos_disponibles >= 0),
    placa             VARCHAR2(10) NOT NULL,
    CONSTRAINT fk_viaje_vehiculo 
        FOREIGN KEY (placa) 
        REFERENCES Vehiculo(placa),
    CONSTRAINT chk_viaje_fechas 
        CHECK (fecha_hora_llegada IS NULL OR fecha_hora_llegada > fecha_hora_salida)
);

-- ==============================================================================
-- 6. TABLA PARADA
-- ==============================================================================
CREATE TABLE Parada (
    id_parada         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ubicacion         VARCHAR2(200) NOT NULL,
    localidad         VARCHAR2(100) NOT NULL,
    id_viaje          NUMBER NOT NULL,
    CONSTRAINT fk_parada_viaje 
        FOREIGN KEY (id_viaje) 
        REFERENCES Viaje(id_viaje) 
        ON DELETE CASCADE
);

-- ==============================================================================
-- 7. TABLA SOLICITUD RESERVA (Tabla Intermedia)
-- ==============================================================================
CREATE TABLE SolicitudReserva (
    id_solicitud      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estado_solicitud  VARCHAR2(20) DEFAULT 'Pendiente' NOT NULL 
                      CONSTRAINT chk_solicitud_estado CHECK (estado_solicitud IN ('Pendiente', 'Aceptado', 'Rechazado', 'Cancelado')),
    id_pasajero       NUMBER NOT NULL,
    id_parada         NUMBER NOT NULL,
    CONSTRAINT fk_solicitud_pasajero 
        FOREIGN KEY (id_pasajero) 
        REFERENCES Pasajero(id_pasajero),
    CONSTRAINT fk_solicitud_parada 
        FOREIGN KEY (id_parada) 
        REFERENCES Parada(id_parada)
);

